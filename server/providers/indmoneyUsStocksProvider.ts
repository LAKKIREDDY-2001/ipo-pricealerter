const MACRO_CACHE_FILE = path.resolve(process.cwd(), 'server', 'data', 'macro-cache.json');
const DEFAULT_USD_INR = 84.45;

/**
 * Read the current live USD/INR exchange rate from macro cache or return fallback
 */
export function getLiveUsdInrRate(): number {
  try {
    if (fs.existsSync(MACRO_CACHE_FILE)) {
      const raw = fs.readFileSync(MACRO_CACHE_FILE, 'utf8');
      const parsed = JSON.parse(raw);
      if (typeof parsed?.usdInr?.rate === 'number' && parsed.usdInr.rate > 0) {
        return Number(parsed.usdInr.rate.toFixed(2));
      }
    }
  } catch {
    // ignore
  }
  return DEFAULT_USD_INR;
}

