function makeDeterministicHistory(base: number, points = 30): Array<{ date: string; open: number; high: number; low: number; close: number; volume: number }> {
  // Deterministic non-random historical reference curve anchored to previousClose/currentPrice
  const series: Array<{ date: string; open: number; high: number; low: number; close: number; volume: number }> = [];
  const endDate = new Date('2026-11-13T00:00:00Z');
  for (let i = points - 1; i >= 0; i--) {
    const d = new Date(endDate.getTime() - i * 86400000);
    if (d.getUTCDay() === 0 || d.getUTCDay() === 6) continue;
    const wave = Math.sin((points - i) * 0.45) * 0.018 + ((points - i) / points - 0.5) * 0.03;
    const close = Number((base * (0.975 + wave)).toFixed(2));
    const open = Number((close * 0.996).toFixed(2));
    const high = Number((Math.max(open, close) * 1.008).toFixed(2));
    const low = Number((Math.min(open, close) * 0.992).toFixed(2));
    series.push({
      date: d.toISOString().slice(0, 10),
      open,
      high,
      low,
      close,
      volume: Math.round(1200000 + (i % 5) * 185000),
    });
  }
  return series;
}

